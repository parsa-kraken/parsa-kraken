#!/usr/bin/env python3
"""
Post-process the GitHub contribution snake SVG so cells STAY LIT after
being visited by the snake (instead of flashing briefly and reverting).

The default snk behavior:
    0%       -> 96.99% : cell is empty (gray)
    96.99%   -> 97.01% : cell briefly flashes its contribution color
    97.01%   -> 100%  : cell reverts to empty (gray)

The user reported this caused a desync issue when we tried to reorder
cells by brightness (bright cells flashed way before the snake body
reached them).

Since the snake's PATH is generated by snk's TSP algorithm and cannot
be easily reordered, the cleanest fix is to:
  1. KEEP the cell timings in their original order (synced with snake body)
  2. MODIFY each cell keyframe so the cell STAYS LIT after being visited
     (i.e., remove the "revert to empty" portion of the keyframe)

The visual effect:
  - Snake body grows along its path through the contribution grid
  - As the snake passes each cell, that cell lights up with its
    contribution color (bright green for level 4, dim green for level 1)
  - The cell STAYS LIT for the rest of the animation (creating a
    satisfying "snake leaves a trail of eaten dots" effect)
  - At end of animation: snake has fully grown, all visited cells are lit
  - On each loop: animation restarts, cells reset to empty, snake regrows

This is more visually pleasing than the default flash-and-revert behavior
and avoids the desync that the previous bright-first reorder caused.

Usage:
  python scripts/reorder_snake.py dist/github-snake.svg
  python scripts/reorder_snake.py dist/github-snake-dark.svg

Idempotent: running twice produces the same output.
"""
from pathlib import Path
import re
import sys


# Pattern matches the original snk keyframe format:
#   @keyframes c0{96.99%{fill:var(--c4)}97.01%,100%{fill:var(--ce)}}
# We need to:
#   - Capture the cell_id (e.g. "0", "1", "a", "b")
#   - Capture the timing percentage (e.g. 96.99)
#   - Capture the contribution level var (e.g. c4)
#   - Replace the whole rule with one that STAYS LIT after the flash
KEYFRAME_RE = re.compile(
    r'@keyframes\s+c(?P<id>[a-z0-9]+)\s*\{'
    r'(?P<pct>[\d.]+)%\{fill:var\(--(?P<lvl>c[1-4])\)\}'
    r'[\d.,%]*\{fill:var\(--ce\)\}'   # the revert-to-empty portion
    r'\}',
    re.IGNORECASE,
)


def patch_keyframes(svg_text):
    """Replace each @keyframes cN{...} rule with a stay-lit version.

    Original: @keyframes c0{96.99%{fill:var(--c4)}97.01%,100%{fill:var(--ce)}}
    Patched:  @keyframes c0{0%{fill:var(--ce)}96.99%{fill:var(--c4)}100%{fill:var(--c4)}}
    """
    patches = []

    def replacer(m):
        cell_id = m.group('id')
        pct = m.group('pct')
        lvl = m.group('lvl').lower()
        # Build the new stay-lit keyframe:
        # - 0% to <pct>%: empty (gray)
        # - <pct>% to 100%: stays at the contribution color (no revert)
        new_kf = (
            f'@keyframes c{cell_id}'
            f'{{0%{{fill:var(--ce)}}'
            f'{pct}%{{fill:var(--{lvl})}}'
            f'100%{{fill:var(--{lvl})}}}}'
        )
        patches.append((cell_id, pct, lvl, new_kf))
        return new_kf

    new_text, n = KEYFRAME_RE.subn(replacer, svg_text)
    return new_text, n


def main():
    if len(sys.argv) < 2:
        print("Usage: reorder_snake.py <path-to-snake.svg> [<path2> ...]")
        sys.exit(1)
    for arg in sys.argv[1:]:
        path = Path(arg)
        if not path.exists():
            print(f"  {path}: NOT FOUND, skipping")
            continue
        original = path.read_text(encoding="utf-8")
        new, n = patch_keyframes(original)
        if new == original:
            print(f"  {path.name}: no changes (already patched or no keyframes)")
        else:
            path.write_text(new, encoding="utf-8")
            print(f"  {path.name}: patched {n} cell keyframes (stay-lit mode)")


if __name__ == "__main__":
    main()
